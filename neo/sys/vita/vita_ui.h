/*
===========================================================================

PS Vita UI art: button glyphs and the controller picture.

The pixels live in one RGBA atlas generated by tools/vita/compose_vita_ui.py
(vita_ui_assets.cpp, zlib-compressed). At runtime it becomes the image and
implicit material "_vitaUiAtlas", and every glyph is a rectangle inside it.

Two things use it:
  - the menu SWFs: their stock Xbox 360 / PS3 prompt bitmaps are matched by
    atlas rectangle at load time and drawn from the Vita atlas instead
    (idSWF::LoadBinary / idSWF::RenderShape)
  - the Controller Layout screen, which draws a Vita picture with the live
    bindings on top of it (Vita_UI_DrawControllerLayout)

===========================================================================
*/
#ifndef __VITA_UI_H__
#define __VITA_UI_H__

struct vitaUiGlyph_t {
    const char* name;
    int x, y, w, h;
};

struct vitaUiSwfGlyph_t {
    const char* swf;     // idSWF filename, e.g. "swf/shell.swf"
    int x, y, w, h;      // the stock bitmap's rectangle in that SWF's atlas
    const char* glyph;   // vitaUiGlyph_t name that replaces it
};

extern const int vitaUiAtlasWidth;
extern const int vitaUiAtlasHeight;
extern const unsigned int vitaUiAtlasCompressedSize;
extern const unsigned char vitaUiAtlasCompressed[];
extern const vitaUiGlyph_t vitaUiGlyphs[];
extern const int vitaUiNumGlyphs;
extern const vitaUiSwfGlyph_t vitaUiSwfGlyphs[];
extern const int vitaUiNumSwfGlyphs;

#ifndef VITA_UI_ASSETS_ONLY

class idMaterial;
class idSWF;
class idVec2;

// Binds the Vita control scheme (vita_ui.cpp). It is the only scheme: there
// are no alternate layouts, no lefty flip and no rebinding on the Vita.
void Vita_ApplyControlScheme();

// Registers the "_vitaUiAtlas" image. Called from CreateIntrinsicImages().
void Vita_UI_CreateImages();

// The atlas material (NULL until the renderer is up).
const idMaterial* Vita_UI_Material();

// Glyph lookup by name; -1 if unknown.
int Vita_UI_FindGlyph(const char* name);
const vitaUiGlyph_t* Vita_UI_Glyph(int index);

// Texture coordinates of a glyph inside the atlas.
void Vita_UI_GlyphST(int index, float& s1, float& t1, float& s2, float& t2);

// Which Vita glyph replaces the stock SWF atlas bitmap at (x, y, w, h), or -1.
int Vita_UI_SwfGlyph(const char* swfName, int x, int y, int w, int h);

// Vita glyph for an engine key (K_JOY1, K_JOY_DPAD_UP, ...), or -1.
int Vita_UI_GlyphForKey(int keyNum);

// Vita glyph for a "<JOY1>"-style tooltip token's key name ("JOY1"), or -1.
int Vita_UI_GlyphForKeyName(const char* keyName);

// Draws the Controller Layout screen full screen - the Vita picture and every
// binding of the scheme - at the given opacity. Called right after the menu
// SWF rendered, only while that screen is up.
void Vita_UI_DrawControllerLayout(idSWF* swf, float alpha);

// Forget the once-per-showing log of the layout geometry.
void Vita_UI_ControllerLayoutShown();

// Which game's scheme the Controller Layout screen shows: 0 DOOM 3: BFG
// (reset at every showing), 1 DOOM I & II. Left / right steps it.
void Vita_UI_SetControllerLayoutGame(int game);
int Vita_UI_GetControllerLayoutGame();

#endif

#endif
