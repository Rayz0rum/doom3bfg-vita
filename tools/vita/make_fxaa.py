#!/usr/bin/env python3
"""Makes the 3D view's FXAA (neo/renderer/vita_fxaa.inc) from NVIDIA's FXAA 3.11.

usage: make_fxaa.py [gcc] [FXAA_3_11.h]
   (defaults: gcc on the PATH, tools/vita/third_party/FXAA_3_11.h)

FXAA 3.11 (Timothy Lottes, NVIDIA) - the user's copy of the official header,
kept in tools/vita/third_party. Its integration checklist, applied:
  (1) defines: FXAA_PC_CONSOLE 1 - the console algorithm (the PS3 / 360 one,
      4 + 2..4 taps, an early exit on low contrast), the lightest of the set,
      the one the Vita's GPU can afford every frame; FXAA_GREEN_AS_LUMA 1 -
      the 3D view copied before the stretch has no luma in its alpha;
      FxaaTexTop -> tex2D (the copy has one mip level), FxaaTex -> sampler2D
  (2) the header is included - here run through the C preprocessor, so the
      engine's shader converter (Cg -> GLSL, RenderProgs_GLSL.cpp) and
      vitaGL's GLSL -> Cg pass see plain code, not the header's macro layers
  (3) FxaaPixelShader is called from the postprocess shader - here its console
      body is inlined into main(), its inputs made locals, its returns
      assignments to the result
  (4) RGBL: green as luma, see (1)
  (5) the constants come from uniforms the stretch pass sets (rpTexGen0S /
      rpTexGen0T, RB_PostProcess): the source's texel size, N, the edge
      sharpness, the edge threshold and its minimum
  (6) fxaaConsolePosPos (the pixel's corners) is computed in the pixel shader
      from pos, half a texel either way, as the header defines it
  (7) the source is sampled bilinear (the stretch's copy is)
The generated main() replaces the stock postprocess shader's (a plain copy)
when vita_fxaa is on.
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GCC = sys.argv[1] if len(sys.argv) > 1 else "gcc"
HEADER = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "third_party", "FXAA_3_11.h")
OUT = os.path.join(HERE, "..", "..", "neo", "renderer", "vita_fxaa.inc")


def preprocess():
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "fxaa_console.c")
        with open(src, "w", encoding="utf-8") as fp:
            fp.write('#define FXAA_PC_CONSOLE 1\n'
                     '#define FXAA_GREEN_AS_LUMA 1\n'
                     '#define FxaaTex sampler2D\n'
                     '#define FxaaTexTop(t, p) tex2D(t, p)\n'
                     '#include "%s"\n' % HEADER.replace("\\", "/"))
        out = subprocess.check_output([GCC, "-E", "-P", "-x", "c", src], text=True)
    return out


def extract_console(code):
    start = code.index("FxaaPixelShader(")
    body_start = code.index("{", start)
    depth = 0
    for i in range(body_start, len(code)):
        if code[i] == "{":
            depth += 1
        elif code[i] == "}":
            depth -= 1
            if depth == 0:
                return code[body_start + 1:i]
    raise SystemExit("FxaaPixelShader's body not found")


def main():
    code = preprocess()
    if "FXAA_PC_CONSOLE" in code:
        raise SystemExit("the preprocessor left FXAA_PC_CONSOLE in the output")
    luma = re.search(r"float FxaaLuma\(float4 rgba\) \{ return (rgba\.\w); \}", code)
    assert luma and luma.group(1) == "rgba.y", "FxaaLuma is not green-as-luma"
    body = extract_console(code)
    # FxaaLuma(x) -> (x).y (green as luma; the function is inlined)
    body = re.sub(r"FxaaLuma\((tex2D\(tex, [^)]*\))\)", r"(\1).y", body)
    assert "FxaaLuma" not in body, body
    # the returns: the early exit and the result
    body = body.replace("return rgbyM;", "{ result.color = rgbyM; return; }")
    body = re.sub(r"return rgbyB;\s*$", "result.color = rgbyB;", body.strip())
    assert "return rgbyB" not in body
    # normalize the header's whitespace a little
    lines = [l.rstrip() for l in body.split("\n") if l.strip()]
    inputs = [
        "// inputs of the header's FxaaPixelShader (integration step 5 and 6)",
        "float2 pos = fragment.texcoord0;",
        "float2 rcpFrame = rpTexGen0S.xy;",
        "float4 fxaaConsolePosPos = pos.xyxy + float4( -0.5, -0.5, 0.5, 0.5 ) * rcpFrame.xyxy;",
        "float4 fxaaConsoleRcpFrameOpt = float4( -rpTexGen0S.z, -rpTexGen0S.z, rpTexGen0S.z, rpTexGen0S.z ) * rcpFrame.xyxy;",
        "float4 fxaaConsoleRcpFrameOpt2 = float4( -2.0, -2.0, 2.0, 2.0 ) * rcpFrame.xyxy;",
        "float fxaaConsoleEdgeSharpness = rpTexGen0S.w;",
        "float fxaaConsoleEdgeThreshold = rpTexGen0T.x;",
        "float fxaaConsoleEdgeThresholdMin = rpTexGen0T.y;",
        "// the source (samp0: the 3D view copied before the stretch)",
        "#define tex samp0",
    ]
    hlsl = ["// NVIDIA FXAA 3.11 (Timothy Lottes), FXAA_PC_CONSOLE with FXAA_GREEN_AS_LUMA,",
            "// generated by tools/vita/make_fxaa.py from the official header - do not edit",
            "void main( PS_IN fragment, out PS_OUT result ) {"]
    hlsl += ["\t" + l for l in inputs]
    hlsl += ["\t" + l.strip() for l in lines]
    hlsl += ["}"]
    text = "\n".join(hlsl).replace("#define tex samp0\n", "")
    # 'tex' is the header's sampler parameter: the shader's samp0
    text = re.sub(r"\btex\b", "samp0", text)
    text = text.replace("\t// the source (samp0: the 3D view copied before the stretch)\n", "")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fp:
        fp.write("// tools/vita/make_fxaa.py: NVIDIA FXAA 3.11, console algorithm, as the postprocess\n")
        fp.write("// shader's main() (RenderProgs_GLSL.cpp, vita_fxaa) - generated, do not edit\n")
        for l in text.split("\n"):
            fp.write('"%s\\n"\n' % l.replace("\\", "\\\\").replace('"', '\\"'))
    print(text)
    print("\n-> %s" % os.path.abspath(OUT))


if __name__ == "__main__":
    main()
