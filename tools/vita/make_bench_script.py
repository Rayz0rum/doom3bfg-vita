#!/usr/bin/env python3
"""Builds the benchmark's built-in script (neo/framework/VitaBench_script.inc)
from benchScan's output (PC test build: "benchScan game/<map> 8" writes
benchmark/scan_<map>.txt in the save folder).

usage: make_bench_script.py <scan dir or files...>
"""
import io
import os
import sys

MAPS = ['alphalabs4', 'enpro', 'cpu']  # the order of the run
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'neo', 'framework', 'VitaBench_script.inc')


def find_scan(args, name):
    for a in args:
        p = a if a.endswith('.txt') else os.path.join(a, 'scan_%s.txt' % name)
        if os.path.basename(p) == 'scan_%s.txt' % name and os.path.exists(p):
            return p
    return None


def main():
    args = sys.argv[1:]
    lines = [
        'title DOOM 3 BFG Vita benchmark: Alpha Labs Sector 4, EnPro Plant, CPU Complex - the most taxing views found by benchScan, then fights',
        'log each map: its 8 heaviest views (hold 3 s, then a full turn over 8 s), then 3 fights of 3-5 monsters with the chaingun and the flashlight',
    ]
    for m in MAPS:
        p = find_scan(args, m)
        if p is None:
            sys.exit('no scan for %s' % m)
        for l in io.open(p, encoding='utf-8'):
            l = l.rstrip('\r\n')
            if l.startswith('//'):
                lines.append('log ' + l[2:].strip())
            elif l:
                lines.append(l)
    lines.append('end')
    out = ['// the benchmark\'s built-in script (VitaBench.cpp) - generated by tools/vita/make_bench_script.py from benchScan\'s output']
    for l in lines:
        out.append('"%s\\n"' % l.replace('\\', '\\\\').replace('"', '\\"'))
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('%d lines -> %s' % (len(lines), os.path.normpath(OUT)))


if __name__ == '__main__':
    main()
