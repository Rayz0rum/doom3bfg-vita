#!/usr/bin/env python3
"""The warnings the game's own data raises, from a full verification run of
the PC test build (same code, same data) - written to
neo/framework/VitaVerify_known_warnings.inc. On the Vita, the verification
counts a warning as serious only when it is not one of these: what the PC run
printed too comes from the data (a missing GUI in a map, a joint a script asks
for), not from the port.

usage: make_known_warnings.py <PC qconsole.log> [more logs...]
"""
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "neo", "framework", "VitaVerify_known_warnings.inc")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    seen = set()
    for path in sys.argv[1:]:
        with open(path, encoding="utf-8", errors="replace") as fp:
            for line in fp:
                m = re.match(r"WARNING: (.*)$", line.rstrip("\r\n"))
                if not m:
                    continue
                text = re.sub(r"\^\d", "", m.group(1)).strip()
                if text and len(text) < 400:
                    seen.add(text)
    keys = sorted(seen)
    with open(OUT, "w", newline="\n", encoding="utf-8") as fp:
        fp.write("// generated by tools/vita/make_known_warnings.py from a PC verification run - the game data's own warnings\n")
        for k in keys:
            fp.write('"%s\\n"\n' % k.replace("\\", "\\\\").replace('"', '\\"'))
    print("%d known warnings -> %s" % (len(keys), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
